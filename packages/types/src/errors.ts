export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode];

/** A single field-level validation problem. */
export interface FieldError {
  field: string;
  message: string;
}

export interface ApiErrorBody {
  code: ErrorCode | string;
  message: string;
  details?: FieldError[];
}
